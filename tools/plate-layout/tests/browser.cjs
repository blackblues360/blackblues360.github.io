// Development-only acceptance test. The website itself has no package dependencies.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');

(async () => {
  const output = process.env.PLATE_TEST_OUTPUT || await fs.mkdtemp(path.join(os.tmpdir(), 'plate-layout-'));
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(process.env.PLATE_BROWSER_PATH ? { executablePath: process.env.PLATE_BROWSER_PATH } : process.platform === 'win32' ? { channel: 'msedge' } : {}) });
  try {
    const context = await browser.newContext({ viewport: { width: 1536, height: 1080 }, acceptDownloads: true });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const base = process.env.PLATE_TEST_URL || 'http://127.0.0.1:8000';
    const toolUrl = `${base}/tools/plate-layout/`;
    const well = id => page.locator(`#plate [data-well="${id}"]`);
    const selected = () => page.locator('#plate [data-well][aria-pressed="true"]').count();
    const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('blackblues.plate-layout.v1')));
    const resetStorage = async () => { await page.evaluate(() => localStorage.removeItem('blackblues.plate-layout.v1')); await page.reload(); await well('A1').waitFor(); };
    const addLabel = async (name, ids) => {
      await page.locator('#deselectAll').click({ force: true });
      for (const id of ids) await well(id).click();
      await page.locator('#labelName').fill(name);
      await page.locator('#applyLabel').click();
    };
    await page.goto(toolUrl);
    await well('H12').waitFor();
    assert.equal(await page.locator('link[rel="icon"]').getAttribute('href'), 'icon.png');
    assert.equal(await page.locator('img.tool-mark').evaluate(image => image.complete && image.naturalWidth > 0), true);
    assert.ok(!(await page.locator('.breadcrumb').textContent()).includes('实验工具'));
    assert.equal(await page.locator('#plate [data-well]').count(), 96);
    for (const [type, last] of [['6', 'B3'], ['12', 'C4'], ['24', 'D6'], ['96', 'H12']]) {
      await page.locator(`[data-type="${type}"]`).click();
      assert.equal(await page.locator('#plate [data-well]').count(), Number(type));
      assert.equal(await well(last).count(), 1);
    }
    await addLabel('Control', ['A1', 'A2', 'B3']);
    const control = (await stored()).labels[0];
    assert.equal(await selected(), 0, 'creating a label clears selection');
    assert.deepEqual((await stored()).ui.selected, [], 'cleared selection is persisted');
    await page.locator('#undo').click();
    assert.equal(await selected(), 3, 'undo restores the selection before application');
    assert.equal((await stored()).wells.A1, null);
    await page.locator('#redo').click();
    assert.equal(await selected(), 0);
    assert.equal((await stored()).wells.A1, control.id);
    await well('A1').click(); await well('A2').click(); await well('B3').click();
    await well('A2').click();
    assert.equal(await selected(), 2);
    assert.equal((await stored()).wells.A2, control.id);
    await addLabel('OVA', ['A1']);
    assert.notEqual((await stored()).wells.A1, control.id);
    await addLabel(' control ', ['B1']);
    assert.equal((await stored()).labels.length, 2);
    assert.equal((await stored()).wells.B1, control.id);
    assert.equal(await selected(), 0, 'same-name label reuse clears selection');
    await well('C1').click(); await well('C2').click();
    await page.locator('#labelName').fill('   '); await page.locator('#applyLabel').click();
    assert.equal(await selected(), 2, 'invalid labels retain the selection');
    await page.locator(`[data-apply-label="${control.id}"]`).click();
    assert.equal(await selected(), 0, 'applying an existing label clears selection');
    await page.locator('#undo').click();
    assert.equal(await selected(), 2);
    assert.equal((await stored()).wells.C1, null);
    await page.locator('#redo').click();
    assert.equal(await selected(), 0);
    await page.locator(`[data-label-color="${control.id}"]`).evaluate(input => { input.value = '#e4b9c9'; input.dispatchEvent(new Event('change', { bubbles: true })); });
    assert.equal(await well('A2').locator('.well-circle').getAttribute('fill'), '#e4b9c9');
    assert.equal(await well('C1').locator('.well-circle').getAttribute('fill'), '#e4b9c9');
    await well('C1').click(); await well('C2').click();
    await page.locator('#clearLabels').click();
    assert.equal((await stored()).wells.C1, null);
    assert.equal((await stored()).wells.B3, control.id);
    await page.locator('#undo').click();
    assert.equal((await stored()).wells.C1, control.id);
    await page.locator('#redo').click();
    assert.equal((await stored()).wells.C1, null);
    await page.locator('#deselectAll').click();
    const start = await well('H1').boundingBox(); const end = await well('H4').boundingBox();
    await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2);
    await page.mouse.down();
    await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 20 });
    await page.mouse.up();
    assert.equal(await selected(), 4, 'paint selection spans H1–H4');
    await page.locator('#undo').click(); assert.equal(await selected(), 0, 'one drag is one undo step');
    await page.locator('#plate [data-row="B"]').click(); assert.equal(await selected(), 12);
    await page.locator('#plate [data-col="3"]').click(); assert.equal(await selected(), 19);
    await page.locator('#plate [data-col="3"]').click(); assert.equal(await selected(), 11);
    await page.locator('#deselectAll').click();
    await well('A1').focus(); await page.keyboard.press('Space');
    await page.keyboard.press('ArrowRight'); await page.keyboard.press('Space');
    assert.equal(await selected(), 2);
    const beforeSwitch = await stored();
    page.once('dialog', dialog => dialog.dismiss());
    await page.locator('[data-type="6"]').click();
    assert.equal((await stored()).plate.type, '96');
    page.once('dialog', dialog => dialog.accept());
    await page.locator('[data-type="6"]').click();
    assert.equal((await stored()).labels.length, 0);
    await page.locator('#undo').click();
    assert.deepEqual(await stored(), beforeSwitch);
    page.once('dialog', dialog => dialog.accept());
    await page.locator(`[data-delete-label="${control.id}"]`).click();
    assert.equal((await stored()).wells.A2, null);
    await page.locator('#undo').click(); assert.equal((await stored()).wells.A2, control.id);
    await page.reload(); await well('A1').waitFor();
    assert.equal((await stored()).wells.A2, control.id);
    assert.equal(await page.locator('#undo').isDisabled(), true, 'history is session-only');
    const beforeReset = await stored();
    page.once('dialog', dialog => dialog.dismiss()); await page.locator('#reset').click();
    assert.deepEqual(await stored(), beforeReset);
    page.once('dialog', dialog => dialog.accept()); await page.locator('#reset').click();
    assert.equal((await stored()).labels.length, 0);
    await page.locator('#undo').click(); assert.deepEqual(await stored(), beforeReset);
    console.log('PASS: icons, breadcrumb, auto-clear after label application, atomic undo/redo, formats, selection, labels, colors, confirmation, persistence');

    await resetStorage();
    await page.locator('#planTitle').fill('BMDC OVA uptake experiment');
    await addLabel('Control', ['A1','A2','A3','A4','B1','B2','B3','B4']);
    await addLabel('OVA', ['A5','A6','A7','A8','B5','B6','B7','B8']);
    await addLabel('LPS', ['A9','A10','A11','A12','B9','B10','B11','B12']);
    await addLabel('OVA + LPS', ['C1','C2','C3','C4','D1','D2','D3','D4']);
    await addLabel('Isotype', ['C5','C6','C7','C8','D5','D6','D7','D8']);
    await addLabel('Blank', ['E1','E2','E3','E4']);
    await well('F1').click(); await well('F2').click(); await well('F3').click(); await well('F4').click();
    assert.equal(await page.locator('#legend .legend-item').count(), 6);
    assert.match(await page.locator('#legendSummary').textContent(), /44/);
    await page.locator('#notice').waitFor({ state: 'hidden' });
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
    for (const format of ['png', 'jpg']) {
      const downloadEvent = page.waitForEvent('download');
      await page.locator(format === 'png' ? '#exportPng' : '#exportJpg').click();
      const download = await downloadEvent;
      assert.equal(download.suggestedFilename(), `BMDC OVA uptake experiment.${format}`);
      const target = path.join(output, `sample.${format}`);
      await download.saveAs(target);
      const bytes = await fs.readFile(target);
      if (format === 'png') assert.equal(bytes.subarray(0, 8).toString('hex'), '89504e470d0a1a0a');
      else assert.equal(bytes.subarray(0, 3).toString('hex'), 'ffd8ff');
      const dimensions = await page.evaluate(async ({ base64, format }) => {
        const image = new Image(); image.src = `data:image/${format === 'jpg' ? 'jpeg' : 'png'};base64,${base64}`;
        await image.decode(); const canvas = document.createElement('canvas'); canvas.width = image.width; canvas.height = image.height;
        const context = canvas.getContext('2d'); context.drawImage(image, 0, 0);
        return { width: image.width, height: image.height, corner: [...context.getImageData(0, 0, 1, 1).data] };
      }, { base64: bytes.toString('base64'), format });
      assert.equal(dimensions.width, 2400);
      assert.ok(dimensions.height > 1600);
      assert.deepEqual(dimensions.corner, [255,255,255,255]);
    }
    await page.locator('#notice').waitFor({ state: 'hidden' });
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.screenshot({ path: path.join(output, 'desktop-1280.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.ok(await page.locator('.plate-scroll').evaluate(element => element.scrollWidth > element.clientWidth));
    await page.setViewportSize({ width: 1536, height: 1080 });
    const unsafe = '<script>window.injected=1</script> & 中文长标签';
    await addLabel(unsafe, ['H12']);
    await page.locator('#planTitle').fill('中文实验 <OVA> & "LPS" '.repeat(7).slice(0, 160));
    assert.equal(await page.evaluate(() => window.injected), undefined);
    const exportCheck = await page.evaluate(async () => {
      const { buildExportSvg } = await import('../plate-layout/core.mjs');
      const data = JSON.parse(localStorage.getItem('blackblues.plate-layout.v1'));
      const output = buildExportSvg(data);
      const parsed = new DOMParser().parseFromString(output.svg, 'image/svg+xml');
      return { parserErrors: parsed.querySelectorAll('parsererror').length, scripts: parsed.querySelectorAll('script').length, text: parsed.documentElement.textContent };
    });
    assert.equal(exportCheck.parserErrors, 0); assert.equal(exportCheck.scripts, 0); assert.ok(exportCheck.text.includes(unsafe));
    const unicodeDownload = page.waitForEvent('download'); await page.locator('#exportPng').click(); await (await unicodeDownload).saveAs(path.join(output, 'unicode.png'));
    await resetStorage();
    for (const format of ['png', 'jpg']) {
      const event = page.waitForEvent('download'); await page.locator(format === 'png' ? '#exportPng' : '#exportJpg').click();
      const download = await event; assert.match(download.suggestedFilename(), /^plate-layout-\d{4}-\d{2}-\d{2}\.(png|jpg)$/);
      await download.saveAs(path.join(output, `blank.${format}`));
    }
    console.log('PASS: reference layout, PNG/JPG signatures and opaque white background, empty and populated exports, long multilingual names, XML safety, desktop/mobile overflow');

    const bounds = await page.evaluate(async () => {
      const { createState, wellIds, assignLabel, nextColor, buildExportSvg } = await import('../plate-layout/core.mjs');
      const state = createState();
      state.plate.title = '长标题 & XML 边界\ufffe ' + 'WW中文'.repeat(30);
      wellIds('96').forEach((id, index) => {
        state.ui.selected = [id];
        assignLabel(state, `${index + 1} ${'WW中文高浓度抗原处理组'.repeat(15)}`, nextColor(state.labels));
      });
      const artwork = buildExportSvg(state);
      const holder = document.createElement('div');
      holder.style.cssText = 'position:absolute;left:-20000px;top:0;width:1200px';
      holder.innerHTML = artwork.svg;
      document.body.append(holder);
      const svgBounds = holder.firstElementChild.getBoundingClientRect();
      const overflowing = [...holder.querySelectorAll('text')].filter(text => {
        const rect = text.getBoundingClientRect();
        return rect.left < svgBounds.left - 1 || rect.right > svgBounds.right + 1 || rect.top < svgBounds.top - 1 || rect.bottom > svgBounds.bottom + 1;
      }).map(text => text.textContent);
      holder.remove();
      localStorage.setItem('blackblues.plate-layout.v1', JSON.stringify(state));
      return { overflowing, height: artwork.height };
    });
    assert.deepEqual(bounds.overflowing, []);
    assert.ok(bounds.height > 5000);
    await page.reload(); await well('H12').waitFor();
    await page.locator('#exportScale').selectOption('3');
    await context.setOffline(true);
    const stressEvent = page.waitForEvent('download'); await page.locator('#exportJpg').click();
    await (await stressEvent).saveAs(path.join(output, '96-long-labels.jpg'));
    await context.setOffline(false);
    const deniedPage = await context.newPage();
    await deniedPage.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('Storage disabled', 'SecurityError'); } }));
    await deniedPage.goto(toolUrl);
    await deniedPage.locator('#plate [data-well="A1"]').click();
    assert.match(await deniedPage.locator('#saveStatus').textContent(), /不可用/);
    assert.equal(await deniedPage.locator('#plate [aria-pressed="true"]').count(), 1);
    await deniedPage.close();
    console.log('PASS: 96 long-label export bounds and actual JPG, offline export, graceful operation when browser storage is disabled');
    await page.goto(`${base}/`);
    await page.waitForFunction(() => document.querySelector('#categoryList').children.length > 0);
    assert.equal(await page.locator('a[href="tools/plate-layout/"]').count(), 1);
    assert.ok((await page.locator('#searchCount').textContent()).includes('/'));
    assert.deepEqual(errors, []);
    console.log('PASS: original homepage navigation; zero uncaught browser errors');
    console.log(`Artifacts: ${output}`);
    await context.close();
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
